#!/usr/bin/env node
// One-off renderer: turns docs/beeui-audit/docs-llms-matrix.json into the
// GitHub issue body text for the phase-06 audit. Not part of the regenerable
// matrix pipeline itself; run manually when preparing the issue.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const noEmDash = (s) => String(s).replace(/—/g, '-').replace(/–/g, '-');

async function main() {
  const jsonPath = path.join(process.cwd(), 'docs', 'beeui-audit', 'docs-llms-matrix.json');
  const data = JSON.parse(await readFile(jsonPath, 'utf8'));
  const rows = data.rows;
  const { summary } = data;

  const lines = [];
  lines.push('## Purpose');
  lines.push('');
  lines.push(
    "Consumer-side audit from BeePOS (a real-world integrator of BeeUI) comparing every checkable item on the human docs site (https://beeui.beemvp.com/docs/**) against the four AI-agent surfaces (llms.txt, llms-full.txt, llms-components.txt, llms-patterns.txt) and /docs/ai/, item by item. This is step 1 and 2 of a three-step audit (build the matrix, compare item by item); step 3 (reality-check against the npm package and BeePOS runtime, then propose which side to fix) is intentionally deferred."
  );
  lines.push('');
  lines.push('## Method');
  lines.push('');
  lines.push(
    'Generated by `node scripts/audit/build-docs-llms-matrix.mjs` in the BeePOS repository (Node 24, no new dependencies, `fetch` + regex HTML stripping, raw responses cached under `scripts/audit/.cache/`). The script fetches the site sitemap, all 4 llms files, /docs/ai/, every /docs/components/<slug>/ page (62), every /docs/patterns/**/<screen>/ page (37), the compatibility/start/theming/accessibility/architecture doc pages, `npm view` output for the 3 published packages, and the installed package .d.ts, then writes a row per checkable item to `docs/beeui-audit/docs-llms-matrix.md` and `.json` with columns `ID | Category | Item | Docs-site value (page URL) | llms value (file, line) | Status | Note`.'
  );
  lines.push('');
  lines.push(
    'A companion script, `node scripts/audit/check-exports-vs-dts.mjs`, compares llms-components.txt exported symbols against the installed `@beemvp/beeui-ui` package `dist/typescript/module/index.d.ts` exports (source "npm .d.ts") as a head start on step 3; its output is folded into the matrix as category D rows.'
  );
  lines.push('');
  lines.push(
    `Total matrix rows: **${data.summary.total}**. Full row-by-row detail (including all "identical" rows) lives in the BeePOS repository at \`docs/beeui-audit/docs-llms-matrix.md\` / \`.json\` (consumer-audit workspace, not this repo) and is not restated in full here.`
  );
  lines.push('');

  lines.push('## Totals by status');
  lines.push('');
  lines.push('| Status | Count |');
  lines.push('|---|---|');
  for (const [status, count] of Object.entries(summary.byStatus)) lines.push(`| ${status} | ${count} |`);
  lines.push('');

  lines.push('## Totals by category');
  lines.push('');
  lines.push('| Category | Total | identical | mismatch | docs-only | llms-only | unverifiable |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const [cat, counts] of Object.entries(summary.byCategory)) {
    lines.push(
      `| ${cat} | ${counts.total} | ${counts.identical || 0} | ${counts.mismatch || 0} | ${counts['docs-only'] || 0} | ${counts['llms-only'] || 0} | ${counts.unverifiable || 0} |`
    );
  }
  lines.push('');

  lines.push(
    '## Mismatch rows (12 total, full detail)'
  );
  lines.push('');
  lines.push('These are direct disagreements: both surfaces make a claim and the claims differ.');
  lines.push('');
  const mismatches = rows.filter((r) => r.status === 'mismatch');
  for (const r of mismatches) {
    lines.push(`### ${r.id} [${r.category}] ${noEmDash(r.item)}`);
    lines.push(`- Docs site: ${noEmDash(r.docsSiteValue)}`);
    lines.push(`- llms: ${noEmDash(r.llmsValue)}`);
    if (r.note) lines.push(`- Note: ${noEmDash(r.note)}`);
    lines.push('');
  }

  lines.push('## docs-only and llms-only rows, grouped by category');
  lines.push('');
  lines.push(
    'A "docs-only" row means the item is present/verifiable on the docs site but absent or unstated in the llms surfaces; "llms-only" is the reverse. Small categories are listed in full; the three large, mechanically-repetitive categories (component contract-section coverage, per-pattern-page existence, and per-link HTTP status) are summarized with counts and matrix row-ID ranges instead of one line per row, to keep this issue readable, full detail for those rows is in the BeePOS matrix file referenced above.'
  );
  lines.push('');

  const nonMismatch = rows.filter((r) => r.status === 'docs-only' || r.status === 'llms-only');
  const byCategory = new Map();
  for (const r of nonMismatch) {
    if (!byCategory.has(r.category)) byCategory.set(r.category, []);
    byCategory.get(r.category).push(r);
  }

  const LARGE_CATEGORY_THRESHOLD = 20;
  for (const [cat, catRows] of byCategory) {
    lines.push(`### ${cat} (${catRows.length} rows)`);
    lines.push('');
    if (catRows.length > LARGE_CATEGORY_THRESHOLD) {
      // Summarize by distinguishing item-name pattern (strip the per-instance slug/name prefix).
      const buckets = new Map();
      for (const r of catRows) {
        const key = r.item.replace(/^[a-zA-Z0-9/_-]+:\s*/, '').replace(/Link target: .+$/, 'Link target: <repo-relative path>').replace(/Pattern page exists: .+$/, 'Pattern page exists: <screen>');
        if (!buckets.has(key)) buckets.set(key, { count: 0, statusCounts: {}, firstId: r.id, lastId: r.id });
        const b = buckets.get(key);
        b.count += 1;
        b.statusCounts[r.status] = (b.statusCounts[r.status] || 0) + 1;
        b.lastId = r.id;
      }
      for (const [key, b] of buckets) {
        const statusStr = Object.entries(b.statusCounts).map(([s, c]) => `${c} ${s}`).join(', ');
        lines.push(`- **${noEmDash(key)}**: ${b.count} rows (${statusStr}), matrix IDs ${b.firstId}-${b.lastId}`);
      }
    } else {
      for (const r of catRows) {
        lines.push(`- **${r.id}** [${r.status}] ${noEmDash(r.item)}`);
        lines.push(`  - Docs site: ${noEmDash(r.docsSiteValue)}`);
        lines.push(`  - llms: ${noEmDash(r.llmsValue)}`);
        if (r.note) lines.push(`  - Note: ${noEmDash(r.note)}`);
      }
    }
    lines.push('');
  }

  lines.push('## Already filed, not re-filed here');
  lines.push('');
  lines.push(
    'The underlying items behind the following matrix rows were already filed from BeePOS findings before this pass and are not restated as new asks: #543 (STATUS/unpublished claims, rows A001-A005, A011-A013), #560 (llms-components.txt and /docs/ai/ never link per-component Props pages, informs the category D "contract sections present" rows), #561 (npm latest dist-tag points at prerelease, row A013), #562 (uniwind generate-artifacts undocumented, informs row C007). This audit\'s new contribution is the systematic link-integrity sweep (category H) and the full component/pattern/ADR/accessibility coverage matrix.'
  );
  lines.push('');

  lines.push('## Step 3 pending');
  lines.push('');
  lines.push(
    'Reality-checking the "identical" rows above (and every "mismatch" row, to decide which side is actually correct) against the installed npm package and BeePOS runtime behavior is deferred to a follow-up pass. `scripts/audit/check-exports-vs-dts.mjs` (in the BeePOS repo) was written now as a head start: it confirms all 62 component export lists match the installed `@beemvp/beeui-ui` `.d.ts` with zero mismatches, so the public component API surface itself is verified consistent across docs, llms, and npm reality already. The remaining step-3 work (ADR-citation resolution, accessibility claim verification, a call on each of the 12 mismatches above) is not done in this pass.'
  );
  lines.push('');

  lines.push('---');
  lines.push('');
  lines.push(
    'Credit: this audit was produced as part of the BeePOS consumer field test of BeeUI (a real integrator building against the public package and docs surfaces only, per docs/beeui-audit/protocol.md in that repo). Tracked in #234.'
  );

  const body = lines.join('\n');
  const outPath = path.join(process.cwd(), 'scripts', 'audit', '.cache', 'github-issue-body.md');
  await writeFile(outPath, body, 'utf8');
  console.log(`Wrote issue body (${body.length} chars) to ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
